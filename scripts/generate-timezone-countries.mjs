// Generates src/components/TimezonePicker/zoneCountries.ts — a compact map of
// IANA zone id → ISO 3166-1 alpha-2 country code.
//
// This is the ONLY timezone data the library ships. Everything else the picker
// needs comes from the platform:
//
//   - the zone list      → Intl.supportedValuesOf('timeZone')
//   - zone display names → Intl.DateTimeFormat(…, { timeZoneName })
//   - country names      → Intl.DisplayNames(locale, { type: 'region' })
//
// There is no native API for zone → country, which is why this file exists.
// It replaced a 100 kB tzData blob that the host had to serve from its web root.
//
// Regenerate with: node scripts/generate-timezone-countries.mjs
// (Requires a tzdb source; see SOURCE below.)

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'

// The original export from the tz database. Kept out of the repo — this script
// is run rarely, and the generated map is what's committed.
const SOURCE = process.argv[2] ?? 'src/data/tzData.json'

const raw = JSON.parse(readFileSync(resolve(SOURCE), 'utf8'))

/** @type {Record<string, string>} */
const map = {}
for (const [id, zone] of Object.entries(raw.zones ?? {})) {
  const country = zone.countries?.[0]
  if (country) map[id] = country
}

const sorted = Object.fromEntries(
  Object.entries(map).sort(([a], [b]) => a.localeCompare(b))
)

const out = `// GENERATED by scripts/generate-timezone-countries.mjs — do not edit by hand.
//
// IANA zone id → ISO 3166-1 alpha-2 country code. Country *names* are not
// stored: \`Intl.DisplayNames\` resolves them, localised, at runtime.
//
// Imported dynamically by TimezonePicker so apps that don't group by country
// never download it.

export const ZONE_COUNTRIES: Record<string, string> = ${JSON.stringify(sorted, null, 2)}

export default ZONE_COUNTRIES
`

const target = 'src/components/TimezonePicker/zoneCountries.ts'
writeFileSync(resolve(target), out)
console.log(
  `Wrote ${target} — ${Object.keys(sorted).length} zones, ` +
    `${(out.length / 1024).toFixed(1)} kB`
)
